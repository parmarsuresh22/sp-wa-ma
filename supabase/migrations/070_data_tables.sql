-- ============================================================
-- 070: data tables — spreadsheets the agent, flows and automations
-- can answer from
--
--   data_tables      — one per uploaded sheet / Google Sheet tab / hand-
--                      made table, attached to a WhatsApp number
--                      (NULL = every number). `columns` is the ordered
--                      list of {key, name}; `access` says who may be
--                      told what:
--                        general — anyone messaging that number;
--                        private — a sender only ever gets the rows
--                                  whose `phone_column` matches the
--                                  number they are writing from.
--   data_table_rows  — the rows, as JSONB keyed by column key.
--                      `phone_key` (last 10 digits of the phone cell)
--                      and `search_text` are derived by trigger so the
--                      browser can edit rows directly under RLS.
--
-- `ai_configs`, `flows` and `automations` each gain `data_table_id`:
-- the one table that responder may read.
--
-- redeem_invitation is redefined to treat a data table (and the wish
-- tables of 067) as account data.
--
-- Idempotent — safe to re-run.
-- ============================================================

CREATE TABLE IF NOT EXISTS data_tables (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id      UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  channel_id      UUID REFERENCES whatsapp_config(id) ON DELETE SET NULL,
  name            TEXT NOT NULL,
  columns         JSONB NOT NULL DEFAULT '[]'::jsonb,
  access          TEXT NOT NULL DEFAULT 'general'
                    CHECK (access IN ('general', 'private')),
  phone_column    TEXT,
  source_type     TEXT NOT NULL DEFAULT 'manual'
                    CHECK (source_type IN ('manual', 'upload', 'google_sheet')),
  source_url      TEXT,
  source_sheet    TEXT,
  source_filename TEXT,
  created_by      UUID,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS data_tables_account_channel_idx
  ON data_tables (account_id, channel_id);

ALTER TABLE data_tables ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS data_tables_select ON data_tables;
CREATE POLICY data_tables_select ON data_tables FOR SELECT
  USING (is_account_member(account_id));
DROP POLICY IF EXISTS data_tables_insert ON data_tables;
CREATE POLICY data_tables_insert ON data_tables FOR INSERT
  WITH CHECK (is_account_member(account_id, 'admin'));
DROP POLICY IF EXISTS data_tables_update ON data_tables;
CREATE POLICY data_tables_update ON data_tables FOR UPDATE
  USING (is_account_member(account_id, 'admin'));
DROP POLICY IF EXISTS data_tables_delete ON data_tables;
CREATE POLICY data_tables_delete ON data_tables FOR DELETE
  USING (is_account_member(account_id, 'admin'));

DROP TRIGGER IF EXISTS set_updated_at ON data_tables;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON data_tables
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- `tenant_id` mirrors the parent table's account (set by trigger, never
-- trusted from the client); deletion cascades through table_id.
CREATE TABLE IF NOT EXISTS data_table_rows (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  table_id    UUID NOT NULL REFERENCES data_tables(id) ON DELETE CASCADE,
  tenant_id   UUID,
  seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
  data        JSONB NOT NULL DEFAULT '{}'::jsonb,
  phone_key   TEXT,
  search_text TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS data_table_rows_table_seq_idx
  ON data_table_rows (table_id, seq);
CREATE INDEX IF NOT EXISTS data_table_rows_table_phone_idx
  ON data_table_rows (table_id, phone_key);

CREATE OR REPLACE FUNCTION public.data_table_rows_derive()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_account UUID;
  v_phone_column TEXT;
  v_digits TEXT;
BEGIN
  SELECT account_id, phone_column INTO v_account, v_phone_column
  FROM data_tables WHERE id = NEW.table_id;

  NEW.tenant_id := v_account;
  NEW.updated_at := now();

  v_digits := regexp_replace(COALESCE(NEW.data ->> v_phone_column, ''), '[^0-9]', '', 'g');
  NEW.phone_key := NULLIF(right(v_digits, 10), '');

  SELECT lower(left(string_agg(value, ' '), 4000)) INTO NEW.search_text
  FROM jsonb_each_text(NEW.data);

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS data_table_rows_derive ON data_table_rows;
CREATE TRIGGER data_table_rows_derive
  BEFORE INSERT OR UPDATE ON data_table_rows
  FOR EACH ROW EXECUTE FUNCTION public.data_table_rows_derive();

-- A new phone column re-keys every row of the table.
CREATE OR REPLACE FUNCTION public.data_tables_rekey_rows()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.phone_column IS DISTINCT FROM OLD.phone_column THEN
    UPDATE data_table_rows SET updated_at = now() WHERE table_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS data_tables_rekey_rows ON data_tables;
CREATE TRIGGER data_tables_rekey_rows
  AFTER UPDATE OF phone_column ON data_tables
  FOR EACH ROW EXECUTE FUNCTION public.data_tables_rekey_rows();

ALTER TABLE data_table_rows ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS data_table_rows_select ON data_table_rows;
CREATE POLICY data_table_rows_select ON data_table_rows FOR SELECT
  USING (is_account_member(tenant_id));
DROP POLICY IF EXISTS data_table_rows_insert ON data_table_rows;
CREATE POLICY data_table_rows_insert ON data_table_rows FOR INSERT
  WITH CHECK (is_account_member(tenant_id, 'admin'));
DROP POLICY IF EXISTS data_table_rows_update ON data_table_rows;
CREATE POLICY data_table_rows_update ON data_table_rows FOR UPDATE
  USING (is_account_member(tenant_id, 'admin'));
DROP POLICY IF EXISTS data_table_rows_delete ON data_table_rows;
CREATE POLICY data_table_rows_delete ON data_table_rows FOR DELETE
  USING (is_account_member(tenant_id, 'admin'));

-- The one table each responder may read.
ALTER TABLE ai_configs
  ADD COLUMN IF NOT EXISTS data_table_id UUID REFERENCES data_tables(id) ON DELETE SET NULL;
ALTER TABLE flows
  ADD COLUMN IF NOT EXISTS data_table_id UUID REFERENCES data_tables(id) ON DELETE SET NULL;
ALTER TABLE automations
  ADD COLUMN IF NOT EXISTS data_table_id UUID REFERENCES data_tables(id) ON DELETE SET NULL;

-- redeem_invitation (from 047), now counting data tables and wishes as
-- account data.
CREATE OR REPLACE FUNCTION public.redeem_invitation(
  p_token_hash TEXT
) RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller_id UUID := auth.uid();
  v_inv account_invitations%ROWTYPE;
  v_old_account_id UUID;
  v_old_account_owner UUID;
  v_has_other_members BOOLEAN;
  v_has_data BOOLEAN;
BEGIN
  IF v_caller_id IS NULL THEN
    RAISE EXCEPTION 'Unauthorized' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_inv
  FROM account_invitations
  WHERE token_hash = p_token_hash
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Invitation not found' USING ERRCODE = '22023';
  END IF;
  IF v_inv.accepted_at IS NOT NULL THEN
    RAISE EXCEPTION 'Invitation has already been redeemed'
      USING ERRCODE = '22023';
  END IF;
  IF v_inv.expires_at <= NOW() THEN
    RAISE EXCEPTION 'Invitation has expired' USING ERRCODE = '22023';
  END IF;

  SELECT p.account_id, a.owner_user_id
  INTO v_old_account_id, v_old_account_owner
  FROM profiles p
  JOIN accounts a ON a.id = p.account_id
  WHERE p.user_id = v_caller_id
  FOR UPDATE OF p, a;

  IF v_old_account_id IS NULL THEN
    RAISE EXCEPTION 'Caller has no profile' USING ERRCODE = '42501';
  END IF;

  IF v_old_account_id = v_inv.account_id THEN
    RAISE EXCEPTION 'You are already a member of this account'
      USING ERRCODE = '23505';
  END IF;

  IF v_old_account_owner <> v_caller_id THEN
    RAISE EXCEPTION 'You are already in a shared account; sign up with a different email to join this one'
      USING ERRCODE = '23505';
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE account_id = v_old_account_id
      AND user_id <> v_caller_id
  ) INTO v_has_other_members;

  IF v_has_other_members THEN
    RAISE EXCEPTION 'Your account has other members; remove them or transfer ownership before joining another account'
      USING ERRCODE = '23505';
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM contacts WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM conversations WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM broadcasts WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM automations WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM automation_logs WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM automation_pending_executions WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM flows WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM flow_runs WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM pipelines WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM deals WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM message_templates WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM tags WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM custom_fields WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM contact_notes WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM whatsapp_config WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM api_keys WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM webhook_endpoints WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM quick_replies WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM notifications WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM ai_configs WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM ai_knowledge_documents WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM ai_knowledge_chunks WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM ai_usage_log WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM contact_wishes WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM wish_schedules WHERE account_id = v_old_account_id
    UNION ALL SELECT 1 FROM data_tables WHERE account_id = v_old_account_id
    LIMIT 1
  ) INTO v_has_data;

  IF v_has_data THEN
    RAISE EXCEPTION 'Your account already contains data; sign up with a different email to join this one'
      USING ERRCODE = '23505';
  END IF;

  UPDATE profiles
  SET account_id = v_inv.account_id,
      account_role = v_inv.role
  WHERE user_id = v_caller_id;

  UPDATE account_invitations
  SET accepted_at = NOW(),
      accepted_by_user_id = v_caller_id
  WHERE id = v_inv.id;

  DELETE FROM accounts WHERE id = v_old_account_id;

  RETURN v_inv.account_id;
END;
$$;

ALTER FUNCTION public.redeem_invitation(TEXT) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.redeem_invitation(TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.redeem_invitation(TEXT) TO authenticated;
