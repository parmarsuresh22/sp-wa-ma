// ============================================================
// Builds the AEDA Forms (FOMS) screens for the portal from the original
// application in foms/, unchanged except for addresses:
//
//   foms/static/**      →  public/aeda-static/**
//   foms/templates/*    →  src/lib/foms/pages.generated.ts
//
// The original lives at the root of its own server ("/", "/projects/1",
// "/api/forms/1"). In the portal its pages live under /aeda and its
// API under /api/aeda, so every such address gains that prefix. Nothing
// else about the screens is touched.
//
// Run after changing anything in foms/:   node scripts/build-aeda.mjs
// ============================================================

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'foms')
const outStatic = path.join(root, 'public', 'aeda-static')

/** Addresses inside JavaScript and HTML: pages → /aeda, API → /api/aeda. */
function rewriteAddresses(text) {
  return (
    text
      // API calls: `/api/…`, '/api/…', "/api/…"
      .replace(/([`'"])\/api\//g, '$1/api/aeda/')
      // Pages: /projects/…, /forms/…, /settings — only at the start of a string.
      .replace(/([`'"])\/(projects|forms)\//g, '$1/aeda/$2/')
      .replace(/([`'"])\/settings(?=[`'"?#])/g, '$1/aeda/settings')
      // The home link.
      .replace(/href="\/"/g, 'href="/aeda"')
      .replace(/href=\\"\/\\"/g, 'href=\\"/aeda\\"')
  )
}

// ---- static files -----------------------------------------------------
fs.rmSync(outStatic, { recursive: true, force: true })
const hash = crypto.createHash('sha1')
for (const dir of ['css', 'js']) {
  fs.mkdirSync(path.join(outStatic, dir), { recursive: true })
  for (const name of fs.readdirSync(path.join(src, 'static', dir)).sort()) {
    const raw = fs.readFileSync(path.join(src, 'static', dir, name), 'utf8')
    const text = dir === 'js' ? rewriteAddresses(raw) : raw
    fs.writeFileSync(path.join(outStatic, dir, name), text)
    hash.update(name).update(text)
  }
}
const version = hash.digest('hex').slice(0, 10)

// ---- templates ----------------------------------------------------------
const read = (name) => fs.readFileSync(path.join(src, 'templates', name), 'utf8').replace(/\r\n/g, '\n')

/** Jinja expressions of the original → plain text and the markers the server fills in. */
function expressions(html) {
  return html
    .replace(/\{\{\s*url_for\('static',\s*filename='([^']+)'\)\s*\}\}/g, '/aeda-static/$1')
    .replace(/\{\{\s*asset_ver\s*\}\}/g, version)
    .replace(/\{\{\s*form_id\s*\}\}/g, '__FORM_ID__')
    .replace(/\{\{\s*project_id\s*\}\}/g, '__PROJECT_ID__')
}

function blocks(html) {
  const out = {}
  const re = /\{%\s*block\s+(\w+)\s*%\}([\s\S]*?)\{%\s*endblock\s*%\}/g
  let m
  while ((m = re.exec(html))) out[m[1]] = m[2]
  return out
}

// The portal's appearance (Settings → Appearance) applied to every page,
// right after the original's own stylesheet so it wins.
const appearance = fs.readFileSync(path.join(root, 'scripts', 'aeda-appearance.html'), 'utf8').replace(/\r\n/g, '\n')
const headBlock = '{% block head %}{% endblock %}'
const rawBase = read('base.html')
if (!rawBase.includes(headBlock)) throw new Error('base.html: the head block was not found')
const base = rawBase.replace(headBlock, () => appearance + headBlock)
const pages = {}
for (const name of ['landing', 'project', 'designer', 'summary', 'fill', 'settings']) {
  const own = blocks(read(`${name}.html`))
  // Fill the page's blocks into the base layout, as Jinja's "extends" does.
  const html = base.replace(/\{%\s*block\s+(\w+)\s*%\}([\s\S]*?)\{%\s*endblock\s*%\}/g, (_all, block, fallback) => own[block] ?? fallback)
  const done = rewriteAddresses(expressions(html))
  const left = done.match(/\{\{[^}]*\}\}|\{%[^%]*%\}/)
  if (left) throw new Error(`${name}.html: an expression was not converted: ${left[0]}`)
  pages[name] = done
}

const banner = `// GENERATED by scripts/build-aeda.mjs from foms/templates — do not edit by hand.
// The original AEDA Forms (FOMS) pages, with their addresses moved under
// /aeda and /api/aeda. __FORM_ID__ and __PROJECT_ID__ are filled in by the
// server for each request.
`
fs.writeFileSync(
  path.join(root, 'src', 'lib', 'foms', 'pages.generated.ts'),
  `${banner}\nexport const AEDA_ASSET_VERSION = ${JSON.stringify(version)}\n\nexport const AEDA_PAGES = ${JSON.stringify(pages, null, 2)} as const\n\nexport type AedaPage = keyof typeof AEDA_PAGES\n`,
)

// ---- a check: no address of the original was left pointing at the root ---
const problems = []
const stray = /([`'"])\/(api\/(?!aeda\/)|projects\/|forms\/|settings[`'"?#]|static\/)/
for (const dir of ['js']) {
  for (const name of fs.readdirSync(path.join(outStatic, dir))) {
    fs.readFileSync(path.join(outStatic, dir, name), 'utf8')
      .split('\n')
      .forEach((line, i) => {
        if (stray.test(line)) problems.push(`${name}:${i + 1}: ${line.trim().slice(0, 120)}`)
      })
  }
}
for (const [name, html] of Object.entries(pages)) {
  html.split('\n').forEach((line, i) => {
    if (stray.test(line) || /href="\/"/.test(line)) problems.push(`${name}.html:${i + 1}: ${line.trim().slice(0, 120)}`)
  })
}
if (problems.length > 0) {
  console.error('Addresses still pointing at the root:\n' + problems.join('\n'))
  process.exit(1)
}
console.log(`AEDA screens built (version ${version}): ${Object.keys(pages).length} pages, static files in public/aeda-static`)
